import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pageUrl, sitemapXml, sourcePages } from './sitemap';
import { SITE_URL } from '../../web/site';
import { WEB_DIR } from './utils';

describe('src/scripts/sitemap.ts - pageUrl, sitemapXml', () => {
    test('the top index is / and a nested index is its directory, slash-terminated', () => {
        assert.equal(pageUrl('index.tsx'), '/');
        assert.equal(pageUrl('about/index.tsx'), '/about/');
        assert.equal(pageUrl('docs/guides/index.tsx'), '/docs/guides/');
    });

    test('every entry is an absolute URL on the production origin', () => {
        const xml = sitemapXml(['index.tsx', 'docs/index.tsx']);
        assert.ok(xml.includes(`<loc>${SITE_URL}/</loc>`));
        assert.ok(xml.includes(`<loc>${SITE_URL}/docs/</loc>`));
        assert.ok(xml.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n<urlset '));
        assert.ok(xml.endsWith('</urlset>\n'));
    });

    // The walk order depends on the filesystem; the file must not.
    test('entries are sorted regardless of the order the pages were found in', () => {
        const a = sitemapXml(['docs/index.tsx', 'index.tsx', 'about/index.tsx']);
        const b = sitemapXml(['about/index.tsx', 'docs/index.tsx', 'index.tsx']);
        assert.equal(a, b);
        const order = [...a.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
        assert.deepEqual(order, [`${SITE_URL}/`, `${SITE_URL}/about/`, `${SITE_URL}/docs/`]);
    });

    test('a path that needs XML escaping is escaped inside <loc>', () => {
        const xml = sitemapXml(['a&b/index.tsx']);
        assert.match(xml, /<loc>[^<]*a&amp;b\/<\/loc>/);
        assert.doesNotMatch(xml, /a&b/);
    });
});

describe('src/scripts/sitemap.ts - sourcePages', () => {
    let project: string;

    before(() => {
        project = fs.mkdtempSync(path.join(os.tmpdir(), 'skrapa-sitemap-'));
        const write = (file: string, body: string) => {
            fs.mkdirSync(path.join(project, path.dirname(file)), { recursive: true });
            fs.writeFileSync(path.join(project, file), body);
        };
        write('index.tsx', 'export function Page() { return <h1>Home</h1>; }');
        write('blog/index.tsx', 'export async function Page() { return <h1>Blog</h1>; }');
        write('team/index.tsx', 'export const Page = () => <h1>Team</h1>;');
        // An index.tsx that is not a page: it exports something else.
        write('components/card/index.tsx', 'export function Card() { return <div></div>; }');
        // Beside a page but not one, like the CLI's own rule.
        write('blog/client.ts', 'console.log(1);');
        write('blog/post.tsx', 'export function Page() {}');
        // Where the CLI does not look for pages, so neither does the sitemap.
        const page = 'export function Page() { return <h1>Not here</h1>; }';
        write('node_modules/pkg/index.tsx', page);
        write('.skrapa/index.tsx', page);
        write('assets/index.tsx', page);
    });

    after(() => fs.rmSync(project, { recursive: true, force: true }));

    test('finds every index.tsx that exports Page, however it is exported', () => {
        assert.deepEqual(sourcePages(project, [path.join(project, 'assets')]).sort(), [
            'blog/index.tsx',
            'index.tsx',
            'team/index.tsx',
        ]);
    });
});

describe('src/scripts/sitemap.test.ts - committed sitemap stays in sync', () => {
    // Regenerated by `npm run build`; this is what catches a page that was
    // added without the regenerated file being committed.
    test('the committed sitemap lists exactly the pages under web/', () => {
        const assets = path.join(WEB_DIR, 'assets');
        const expected = sitemapXml(sourcePages(WEB_DIR, [assets]));
        const file = path.join(assets, 'sitemap.xml');
        const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf-8') : '';
        assert.equal(
            actual,
            expected,
            'web/assets/sitemap.xml is behind web/. Run `npm run build` and commit the result.'
        );
    });
});
